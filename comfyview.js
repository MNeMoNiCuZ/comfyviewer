function loadWorkflow(data, name) {
  if (!data || !Array.isArray(data.nodes)) {
    if (data && typeof data === 'object' && Object.values(data).some(v => v && v.class_type)) {
      throw new Error('This is an API-format prompt, not a UI workflow. Export with "Save" (not "Save (API format)").');
    }
    throw new Error('Not a ComfyUI workflow: no "nodes" array.');
  }

  raw = data;
  fileName = name || 'workflow.json';
  nodes = [];
  nodeById = new Map();
  selection = new Set();

  for (const n of data.nodes) {
    const [w, h] = sizeOf(n.size);
    const v = {
      raw: n,
      id: n.id,
      type: n.type || 'Node',
      title: n.title || n.type || 'Node',
      x: (n.pos && (n.pos[0] ?? n.pos['0'])) || 0,
      y: (n.pos && (n.pos[1] ?? n.pos['1'])) || 0,
      w: Math.max(w || 140, MIN_W),
      h: Math.max(h || 40, MIN_H),
      color: n.color || C.nodeColor,
      bgcolor: n.bgcolor || C.nodeBg,
      collapsed: !!(n.flags && n.flags.collapsed),
      mode: n.mode || 0,
      inputs: (n.inputs || []).filter(s => s),
      outputs: (n.outputs || []).filter(s => s),
      widgets: buildWidgets(n),
    };
    v.minW = Math.min(140, v.w);
    v.minH = Math.min(contentHeight(v), v.h);
    nodes.push(v);
    nodeById.set(v.id, v);
  }

  links = normaliseLinks(data);
  groups = (data.groups || []).map(g => ({
    raw: g,
    title: g.title || '',
    b: (g.bounding || [0, 0, 100, 100]).slice(),
    color: g.color || '#3f789e',
    font: g.font_size || 24,
  }));

  order = nodes.map((_, i) => i);
  analysePacks();
  document.getElementById('drop').classList.add('hidden');
  document.getElementById('info').textContent =
    `${fileName}: ${nodes.length} nodes, ${links.length} links` + (groups.length ? `, ${groups.length} groups` : '') +
    (report.packs.length ? `, ${report.packs.length} node pack${report.packs.length > 1 ? 's' : ''}` : '');
  fit();
}

function normaliseLinks(data) {
  const out = [];
  for (const l of (data.links || [])) {
    let id, from, fromSlot, to, toSlot, type;
    if (Array.isArray(l)) {
      [id, from, fromSlot, to, toSlot, type] = l;
    } else if (l && typeof l === 'object') {
      id = l.id;
      from = l.origin_id; fromSlot = l.origin_slot;
      to = l.target_id; toSlot = l.target_slot;
      type = l.type;
    } else continue;
    out.push({ id, from, fromSlot: fromSlot | 0, to, toSlot: toSlot | 0, type });
  }
  return out;
}

function buildWidgets(n) {
  let values = n.widgets_values;
  if (values && !Array.isArray(values) && typeof values === 'object') values = Object.values(values);
  if (!Array.isArray(values) || !values.length) return [];

  const names = WIDGETS[n.type] || null;
  // Widgets converted to input slots are drawn as slots, not rows.
  const converted = new Set((n.inputs || [])
    .filter(s => s && (s.widget || s.widget === ''))
    .map(s => (s.widget && s.widget.name) || s.name));

  // Every widget was dragged out into an input slot, so the node body has no
  // rows at all. True of things like ConcatStringSingle, whose stored height
  // leaves no room for any.
  if (converted.size && converted.size >= values.length) return [];

  const rows = [];
  for (let i = 0; i < values.length; i++) {
    const name = names && i < names.length ? names[i] : null;
    if (name && converted.has(name)) continue;
    const v = values[i];
    if (v === null || v === undefined) continue;
    rows.push({ name, value: v, kind: widgetKind(name, v) });
  }

  // widgets_values holds every widget, converted ones included, so ComfyUI draws
  // exactly (values - converted) rows. When the node's widget names are unknown
  // we cannot tell which ones were converted, but we can still honour the count.
  const budget = values.length - converted.size;
  if (rows.length > budget) rows.length = Math.max(0, budget);
  return rows;
}

function widgetKind(name, v) {
  if (typeof v === 'boolean') return 'toggle';
  if (typeof v === 'number') return 'number';
  if (typeof v === 'string' && (v.includes('\n') || v.length > 48)) return 'text';
  if (name === 'text' || name === 'text_g' || name === 'text_l') return 'text';
  return 'combo';
}

/* ------------------------------------------------------------- pack analysis */

/* Work out which pack every node comes from, and build the report model.
 * Packs are ordered by how many nodes they contribute, so the biggest
 * dependency always gets the first color. */
function analysePacks() {
  const byPack = new Map();
  const core = new Map();
  const unknown = new Map();

  for (const n of nodes) {
    if (CORE.has(n.type)) {
      core.set(n.type, (core.get(n.type) || 0) + 1);
      n.packKey = null;
      n.packName = null;
      continue;
    }
    const found = packsFor(n.type);
    if (!found) {
      unknown.set(n.type, (unknown.get(n.type) || 0) + 1);
      n.packKey = '?';
      n.packName = 'unrecognised';
      continue;
    }
    const key = found[0][1];
    let p = byPack.get(key);
    if (!p) {
      p = { key, title: found[0][0], url: packUrl(key), types: new Map(), count: 0, alt: new Set() };
      byPack.set(key, p);
    }
    p.count++;
    p.types.set(n.type, (p.types.get(n.type) || 0) + 1);
    for (let i = 1; i < found.length; i++) p.alt.add(found[i][0]);
    n.packKey = key;
    n.packName = p.title;
  }

  const packs = [...byPack.values()].sort((a, b) => b.count - a.count || a.title.localeCompare(b.title));
  packs.forEach((p, i) => { p.color = packColor(i); });
  const colorByKey = new Map(packs.map(p => [p.key, p.color]));
  for (const n of nodes) {
    n.packColor = n.packKey === '?' ? UNKNOWN_COLOR : (n.packKey ? colorByKey.get(n.packKey) : null);
  }

  report = {
    packs,
    core: [...core.entries()].sort((a, b) => b[1] - a[1]),
    unknown: [...unknown.entries()].sort((a, b) => b[1] - a[1]),
  };
  renderReport();
}

/* -------------------------------------------------------------- slot layout */

function nodeW(n) { return n.collapsed ? collapsedWidth(n) : n.w; }
function nodeH(n) { return n.collapsed ? 0 : n.h; }

function slotPos(node, isInput, i) {
  if (node.collapsed) {
    const w = collapsedWidth(node);
    return isInput ? [node.x, node.y - TITLE_H / 2] : [node.x + w, node.y - TITLE_H / 2];
  }
  const x = isInput ? node.x + SLOT_H * 0.5 : node.x + node.w + 1 - SLOT_H * 0.5;
  return [x, node.y + (i + 0.7) * SLOT_H];
}

function collapsedWidth(node) {
  ctx.font = '14px Arial';
  return Math.max(COLLAPSED_WIDTH, ctx.measureText(node.title).width + 40);
}

/* The smallest a node may be dragged: enough for its slots and widget rows.
 * Never larger than the size the file already gave it, so nothing jumps. */
function contentHeight(n) {
  let h = Math.max(n.inputs.length, n.outputs.length) * SLOT_H + 4;
  for (const rw of n.widgets) h += (rw.kind === 'text' ? 42 : WIDGET_H) + 4;
  return Math.max(MIN_H, h + 4);
}

function widgetsStartY(node) {
  const rows = Math.max(node.inputs.length, node.outputs.length);
  return rows * SLOT_H + 4;
}

/* ------------------------------------------------------------------ drawing */

function resize() {
  const dpr = window.devicePixelRatio || 1;
  canvas.width = Math.floor(innerWidth * dpr);
  canvas.height = Math.floor(innerHeight * dpr);
  canvas.style.width = innerWidth + 'px';
  canvas.style.height = innerHeight + 'px';
  dirty = true;
}

function draw() {
  if (dirty) {
    dirty = false;
    render();
  }
  requestAnimationFrame(draw);
}

function render() {
  const dpr = window.devicePixelRatio || 1;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.fillStyle = C.bg;
  ctx.fillRect(0, 0, innerWidth, innerHeight);

  drawGrid();

  ctx.save();
  ctx.translate(view.x, view.y);
  ctx.scale(view.scale, view.scale);

  for (const g of groups) drawGroup(g);
  for (const l of links) drawLink(l);
  for (const i of order) drawNode(nodes[i]);
  if (selection.size) for (const i of order) drawSelectionRing(nodes[i]);
  if (settings.labels) for (const i of order) drawPackLabel(nodes[i]);

  ctx.restore();

  if (marquee) drawMarquee();
}

function drawGrid() {
  const step = 50 * view.scale;
  if (step < 6) return;
  const ox = view.x % step, oy = view.y % step;
  ctx.lineWidth = 1;
  ctx.strokeStyle = C.grid;
  ctx.beginPath();
  for (let x = ox; x < innerWidth; x += step) { ctx.moveTo(x + 0.5, 0); ctx.lineTo(x + 0.5, innerHeight); }
  for (let y = oy; y < innerHeight; y += step) { ctx.moveTo(0, y + 0.5); ctx.lineTo(innerWidth, y + 0.5); }
  ctx.stroke();

  const big = step * 5;
  if (big < 24) return;
  const bx = view.x % big, by = view.y % big;
  ctx.strokeStyle = C.gridMajor;
  ctx.beginPath();
  for (let x = bx; x < innerWidth; x += big) { ctx.moveTo(x + 0.5, 0); ctx.lineTo(x + 0.5, innerHeight); }
  for (let y = by; y < innerHeight; y += big) { ctx.moveTo(0, y + 0.5); ctx.lineTo(innerWidth, y + 0.5); }
  ctx.stroke();
}

function drawMarquee() {
  const x = view.x + Math.min(marquee.x0, marquee.x1) * view.scale;
  const y = view.y + Math.min(marquee.y0, marquee.y1) * view.scale;
  const w = Math.abs(marquee.x1 - marquee.x0) * view.scale;
  const h = Math.abs(marquee.y1 - marquee.y0) * view.scale;
  ctx.fillStyle = 'rgba(74,158,255,0.12)';
  ctx.fillRect(x, y, w, h);
  ctx.strokeStyle = C.marquee;
  ctx.lineWidth = 1;
  ctx.strokeRect(x + 0.5, y + 0.5, w, h);
}

function drawGroup(g) {
  const [x, y, w, h] = g.b;
  ctx.globalAlpha = 0.5;
  ctx.fillStyle = g.color;
  roundRect(x, y, w, h, ROUND);
  ctx.fill();
  ctx.globalAlpha = 1;

  ctx.strokeStyle = g.color;
  ctx.lineWidth = 2;
  ctx.stroke();

  if (selectedGroup === g) {
    const gap = Math.max(4, 5 / view.scale);
    ctx.save();
    roundRect(x - gap, y - gap, w + gap * 2, h + gap * 2, ROUND + gap);
    ctx.strokeStyle = 'rgba(0,0,0,0.75)';
    ctx.lineWidth = Math.max(5, 6 / view.scale);
    ctx.stroke();
    ctx.strokeStyle = C.selected;
    ctx.lineWidth = Math.max(2.5, 3.5 / view.scale);
    ctx.stroke();
    ctx.restore();
  }

  ctx.fillStyle = g.color;
  ctx.font = `${g.font}px Arial`;
  ctx.textAlign = 'left';
  ctx.textBaseline = 'alphabetic';
  ctx.fillText(g.title, x + 6, y + g.font);

  // resize grip, bottom-right
  ctx.globalAlpha = 0.6;
  ctx.beginPath();
  ctx.moveTo(x + w, y + h - 14);
  ctx.lineTo(x + w, y + h);
  ctx.lineTo(x + w - 14, y + h);
  ctx.closePath();
  ctx.fill();
  ctx.globalAlpha = 1;
}

function drawLink(l) {
  const a = nodeById.get(l.from);
  const b = nodeById.get(l.to);
  if (!a || !b) return;
  const [x1, y1] = slotPos(a, false, l.fromSlot);
  const [x2, y2] = slotPos(b, true, l.toSlot);

  const dist = Math.max(40, Math.abs(x2 - x1) * 0.25);
  const color = typeColor(l.type);
  const faded = a.mode === 2 || b.mode === 2 || a.mode === 4 || b.mode === 4;

  ctx.globalAlpha = faded ? 0.35 : 1;
  ctx.strokeStyle = color;
  ctx.lineWidth = 3;
  ctx.beginPath();
  ctx.moveTo(x1, y1);
  ctx.bezierCurveTo(x1 + dist, y1, x2 - dist, y2, x2, y2);
  ctx.stroke();

  ctx.fillStyle = color;
  ctx.beginPath();
  ctx.arc((x1 + x2) / 2, (y1 + y2) / 2, 4, 0, Math.PI * 2);
  ctx.fill();
  ctx.globalAlpha = 1;
}

function drawNode(node) {
  const isSel = selection.has(node);
  ctx.save();

  if (node.mode === 2) ctx.globalAlpha = 0.4;          // muted / "never"
  const bypass = node.mode === 4;

  const w = nodeW(node);
  const h = nodeH(node);

  ctx.shadowColor = 'rgba(0,0,0,0.5)';
  ctx.shadowBlur = 6;
  ctx.shadowOffsetX = 2;
  ctx.shadowOffsetY = 2;

  if (!node.collapsed) {
    ctx.fillStyle = bypass ? '#FF00FF' : node.bgcolor;
    roundRectC(node.x, node.y, w, h, ROUND, [false, false, true, true]);
    ctx.fill();
  }

  ctx.fillStyle = bypass ? '#A0A' : node.color;
  roundRectC(node.x, node.y - TITLE_H, w, TITLE_H, ROUND,
    node.collapsed ? [true, true, true, true] : [true, true, false, false]);
  ctx.fill();
  ctx.shadowColor = 'transparent';
  ctx.shadowBlur = 0;
  ctx.shadowOffsetX = 0;
  ctx.shadowOffsetY = 0;

  // outline around title + body
  ctx.strokeStyle = C.border;
  ctx.lineWidth = 1;
  roundRect(node.x - 0.5, node.y - TITLE_H - 0.5, w + 1, h + TITLE_H + 1, ROUND);
  ctx.stroke();

  if (settings.highlight && node.packColor) {      // stock nodes stay unmarked
    const hc = node.packColor;
    ctx.save();
    ctx.strokeStyle = hc;
    ctx.lineWidth = 2;
    ctx.shadowColor = hc;
    ctx.shadowBlur = 14;
    roundRect(node.x - 1, node.y - TITLE_H - 1, w + 2, h + TITLE_H + 2, ROUND);
    ctx.stroke();
    ctx.stroke();          // twice, so the glow reads at low zoom
    ctx.restore();
  }

  // title box + text
  ctx.fillStyle = node.raw.boxcolor || C.boxColor;
  roundRect(node.x + 8, node.y - TITLE_H + 10, 10, 10, 2);
  ctx.fill();

  ctx.fillStyle = isSel ? C.selected : C.titleText;
  ctx.font = '14px Arial';
  ctx.textAlign = 'left';
  ctx.textBaseline = 'middle';
  ctx.fillText(ellipsize(node.title, w - 34), node.x + 24, node.y - TITLE_H / 2 + 1);

  if (node.collapsed) {
    drawCollapsedSlots(node, w);
    ctx.restore();
    return;
  }

  ctx.save();
  roundRectC(node.x, node.y, w, h, ROUND, [false, false, true, true]);
  ctx.clip();

  drawSlots(node);
  drawWidgets(node);

  ctx.restore();

  // resize grip, bottom-right (LiteGraph draws the same triangle)
  ctx.fillStyle = 'rgba(255,255,255,0.25)';
  ctx.beginPath();
  ctx.moveTo(node.x + w - 1, node.y + h - 13);
  ctx.lineTo(node.x + w - 1, node.y + h - 1);
  ctx.lineTo(node.x + w - 13, node.y + h - 1);
  ctx.closePath();
  ctx.fill();

  ctx.restore();
}

/* A thick white ring set well clear of the pack glow, drawn in its own pass so
 * no neighbouring node can paint over it. */
function drawSelectionRing(node) {
  if (!selection.has(node)) return;
  const w = nodeW(node);
  const h = nodeH(node);
  const gap = Math.max(5, 7 / view.scale);          // clears the glow
  const lw = Math.max(2.5, 3.5 / view.scale);       // ~3.5 screen px at any zoom

  ctx.save();
  roundRect(node.x - gap, node.y - TITLE_H - gap, w + gap * 2, h + TITLE_H + gap * 2, ROUND + gap);

  ctx.strokeStyle = 'rgba(0,0,0,0.75)';             // dark backing, so the white
  ctx.lineWidth = lw + Math.max(2, 3 / view.scale); // reads over any background
  ctx.stroke();

  ctx.strokeStyle = C.selected;
  ctx.lineWidth = lw;
  ctx.stroke();
  ctx.restore();
}

/* A small tag sitting just outside the top-right corner, naming the pack the
 * node needs. Stock nodes get none. */
function drawPackLabel(node) {
  if (!node.packColor || !node.packName) return;
  const w = nodeW(node);
  ctx.font = '11px Arial';
  const text = ellipsize(node.packName, Math.max(90, w));
  const tw = ctx.measureText(text).width;
  const bw = tw + 12;
  const bh = 16;
  const bx = node.x + w - bw;
  const by = node.y - TITLE_H - bh - 3;

  ctx.save();
  ctx.fillStyle = 'rgba(20,20,20,0.92)';
  roundRect(bx, by, bw, bh, 4);
  ctx.fill();
  ctx.strokeStyle = node.packColor;
  ctx.lineWidth = 1;
  ctx.stroke();

  ctx.fillStyle = node.packColor;
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  ctx.fillText(text, bx + bw / 2, by + bh / 2 + 0.5);
  ctx.restore();
}

function drawCollapsedSlots(node, w) {
  const y = node.y - TITLE_H / 2;
  if (node.inputs.length) {
    ctx.fillStyle = typeColor(node.inputs[0].type);
    ctx.beginPath(); ctx.arc(node.x, y, 4, 0, Math.PI * 2); ctx.fill();
  }
  if (node.outputs.length) {
    ctx.fillStyle = typeColor(node.outputs[0].type);
    ctx.beginPath(); ctx.arc(node.x + w, y, 4, 0, Math.PI * 2); ctx.fill();
  }
}

function drawSlots(node) {
  ctx.font = '12px Arial';
  ctx.textBaseline = 'middle';

  node.inputs.forEach((s, i) => {
    const [x, y] = slotPos(node, true, i);
    ctx.fillStyle = typeColor(s.type);
    ctx.beginPath();
    if (s.shape === 1) ctx.rect(x - 4, y - 4, 8, 8); else ctx.arc(x, y, 4, 0, Math.PI * 2);
    ctx.fill();
    if (s.link === null || s.link === undefined) {
      ctx.fillStyle = node.bgcolor;
      ctx.beginPath(); ctx.arc(x, y, 2, 0, Math.PI * 2); ctx.fill();
    }
    ctx.fillStyle = C.text;
    ctx.textAlign = 'left';
    ctx.fillText(ellipsize(String(s.name ?? s.type ?? ''), node.w * 0.5), x + 10, y);
  });

  node.outputs.forEach((s, i) => {
    const [x, y] = slotPos(node, false, i);
    ctx.fillStyle = typeColor(s.type);
    ctx.beginPath();
    if (s.shape === 1) ctx.rect(x - 4, y - 4, 8, 8); else ctx.arc(x, y, 4, 0, Math.PI * 2);
    ctx.fill();
    if (!s.links || !s.links.length) {
      ctx.fillStyle = node.bgcolor;
      ctx.beginPath(); ctx.arc(x, y, 2, 0, Math.PI * 2); ctx.fill();
    }
    ctx.fillStyle = C.text;
    ctx.textAlign = 'right';
    ctx.fillText(ellipsize(String(s.name ?? s.type ?? ''), node.w * 0.5), x - 10, y);
  });
}

function drawWidgets(node) {
  if (!node.widgets.length) return;
  let y = node.y + widgetsStartY(node);
  const x = node.x + WIDGET_MARGIN;
  const w = node.w - WIDGET_MARGIN * 2;
  const bottom = node.y + node.h - 4;

  // Multiline text widgets grow to fill whatever space the node has left.
  const textCount = node.widgets.filter(r => r.kind === 'text').length;
  const fixed = node.widgets.filter(r => r.kind !== 'text').length * (WIDGET_H + 4);
  const textH = textCount ? Math.max(40, (bottom - y - fixed - textCount * 4) / textCount) : 0;

  // The stored node height is what ComfyUI itself laid out, so it is the
  // authority: a row that will not fit inside it is a row ComfyUI did not draw.
  for (const rw of node.widgets) {
    if (bottom - y < 16) break;
    if (rw.kind === 'text') {
      drawTextWidget(x, y, w, Math.min(textH, bottom - y), rw);
      y += textH + 4;
    } else {
      if (y + WIDGET_H > bottom + 1) break;
      drawRowWidget(x, y, w, WIDGET_H, rw);
      y += WIDGET_H + 4;
    }
  }
}

function drawRowWidget(x, y, w, h, rw) {
  ctx.fillStyle = C.widgetBg;
  roundRect(x, y, w, h, h * 0.5);
  ctx.fill();
  ctx.strokeStyle = C.widgetOutline;
  ctx.lineWidth = 1;
  ctx.stroke();

  ctx.font = '12px Arial';
  ctx.textBaseline = 'middle';
  const cy = y + h * 0.5;

  const arrows = rw.kind === 'number' || rw.kind === 'combo';
  if (arrows) {
    ctx.fillStyle = C.widgetText2;
    ctx.textAlign = 'center';
    ctx.fillText('◀', x + 12, cy);
    ctx.fillText('▶', x + w - 12, cy);
  }

  const pad = arrows ? 22 : 10;
  let value = rw.kind === 'number' ? fmtNumber(rw.value) : String(rw.value);
  if (rw.kind === 'toggle') value = rw.value ? 'true' : 'false';

  let nameW = 0;
  if (rw.name) {
    ctx.fillStyle = C.widgetText2;
    ctx.textAlign = 'left';
    nameW = Math.min(ctx.measureText(rw.name).width, w * 0.55);
    ctx.fillText(ellipsize(rw.name, w * 0.55), x + pad, cy);
  }
  // Values always sit on the right, named or not. ComfyUI never centres them.
  ctx.fillStyle = C.widgetText;
  ctx.textAlign = 'right';
  ctx.fillText(ellipsize(value, w - pad * 2 - (nameW ? nameW + 8 : 0)), x + w - pad, cy);
}

function drawTextWidget(x, y, w, h, rw) {
  if (h <= 6) return;
  ctx.fillStyle = C.widgetBg;
  roundRect(x, y, w, h, 4);
  ctx.fill();
  ctx.strokeStyle = '#4a4a4a';
  ctx.lineWidth = 1;
  ctx.stroke();

  ctx.save();
  ctx.beginPath();
  ctx.rect(x + 4, y + 2, w - 8, h - 4);
  ctx.clip();

  ctx.font = '12px Arial';
  ctx.textAlign = 'left';
  ctx.textBaseline = 'top';
  ctx.fillStyle = C.widgetText;

  const lines = wrap(String(rw.value), w - 12);
  let ty = y + 5;
  for (const line of lines) {
    if (ty > y + h - 12) break;
    ctx.fillText(line, x + 6, ty);
    ty += 15;
  }
  ctx.restore();
}

const wrapCache = new Map();
function wrap(text, maxW) {
  const key = maxW + '|' + text;
  const hit = wrapCache.get(key);
  if (hit) return hit;
  const out = [];
  for (const para of text.split('\n')) {
    if (!para) { out.push(''); continue; }
    let line = '';
    for (const word of para.split(' ')) {
      const test = line ? line + ' ' + word : word;
      if (ctx.measureText(test).width > maxW && line) { out.push(line); line = word; }
      else line = test;
    }
    out.push(line);
    if (out.length > 200) break;
  }
  if (wrapCache.size > 400) wrapCache.clear();
  wrapCache.set(key, out);
  return out;
}

/* ------------------------------------------------------------- hit testing */

function toGraph(cx, cy) {
  return [(cx - view.x) / view.scale, (cy - view.y) / view.scale];
}

// Outer rect of a node, title bar included.
function nodeRect(n) {
  return [n.x, n.y - TITLE_H, nodeW(n), nodeH(n) + TITLE_H];
}

function nodeAt(gx, gy) {
  for (let i = order.length - 1; i >= 0; i--) {
    const n = nodes[order[i]];
    const [x, y, w, h] = nodeRect(n);
    if (gx >= x && gx <= x + w && gy >= y && gy <= y + h) return n;
  }
  return null;
}

/* Which edge/corner of a rect the point is on, or null. Returns one of
 * nw n ne e se s sw w. */
function handleAt(rect, gx, gy, want, out) {
  const [x, y, w, h] = rect;
  // never let the grab zone swallow the whole thing at low zoom
  const tol = Math.min(want, w * 0.25, h * 0.25);
  // the zone reaches barely outside the border, just enough to absorb pointer
  // rounding, not enough to steal clicks aimed at a neighbour
  if (gx < x - out || gx > x + w + out || gy < y - out || gy > y + h + out) return null;
  const left = Math.abs(gx - x) <= tol;
  const right = Math.abs(gx - (x + w)) <= tol;
  const top = Math.abs(gy - y) <= tol;
  const bottom = Math.abs(gy - (y + h)) <= tol;
  if (top && left) return 'nw';
  if (top && right) return 'ne';
  if (bottom && left) return 'sw';
  if (bottom && right) return 'se';
  if (left) return 'w';
  if (right) return 'e';
  if (top) return 'n';
  if (bottom) return 's';
  return null;
}

const CURSORS = {
  nw: 'nwse-resize', se: 'nwse-resize',
  ne: 'nesw-resize', sw: 'nesw-resize',
  n: 'ns-resize', s: 'ns-resize',
  e: 'ew-resize', w: 'ew-resize',
};

/* What is under the pointer: a node resize handle, a node, a group handle,
 * a group title, or nothing. */
function probe(gx, gy) {
  const tol = HANDLE / view.scale;
  const out = 2 / view.scale;

  for (let i = order.length - 1; i >= 0; i--) {
    const n = nodes[order[i]];
    // the collapse dot wins over the resize edge it sits near
    if (inTitleBox(n, gx, gy)) return { kind: 'node', node: n };
    if (!n.collapsed) {
      const hnd = handleAt(nodeRect(n), gx, gy, tol, out);
      // the top edge is the title bar; dragging it should move, not resize
      if (hnd && hnd !== 'n') return { kind: 'node-resize', node: n, handle: hnd };
    }
    const [x, y, w, h] = nodeRect(n);
    if (gx >= x && gx <= x + w && gy >= y && gy <= y + h) return { kind: 'node', node: n };
  }

  for (let i = groups.length - 1; i >= 0; i--) {
    const g = groups[i];
    const [x, y, w] = g.b;
    const inTitle = gx >= x && gx <= x + w && gy >= y && gy <= y + g.font + 10;
    const hnd = handleAt(g.b, gx, gy, tol, out);
    // the title bar drags the box; only its corners still resize, so the top
    // edge handle never swallows the whole strip
    if (hnd && !(inTitle && hnd === 'n')) return { kind: 'group-resize', group: g, handle: hnd };
    if (inTitle) return { kind: 'group', group: g };
  }
  return { kind: 'canvas' };
}

function nodesInGroup(g) {
  const [x, y, w, h] = g.b;
  return nodes.filter(n => {
    const cx = n.x + nodeW(n) / 2, cy = n.y + nodeH(n) / 2;
    return cx >= x && cx <= x + w && cy >= y && cy <= y + h;
  });
}

/* --------------------------------------------------------------- interaction */

let drag = null;

function bringToFront(node) {
  const idx = nodes.indexOf(node);
  const at = order.indexOf(idx);
  if (at >= 0) order.splice(at, 1);
  order.push(idx);
}

canvas.addEventListener('contextmenu', e => e.preventDefault());

// The title dot, which toggles collapse on click (as in ComfyUI).
function inTitleBox(n, gx, gy) {
  return gx >= n.x + 6 && gx <= n.x + 20 && gy >= n.y - TITLE_H + 8 && gy <= n.y - TITLE_H + 22;
}

canvas.addEventListener('pointerdown', e => {
  stopRename(true);
  closeMenu();
  canvas.setPointerCapture(e.pointerId);
  const [gx, gy] = toGraph(e.offsetX, e.offsetY);

  // right / middle button, or space-less shift-drag: pan
  if (e.button === 1 || e.button === 2) {
    drag = { mode: 'pan', sx: e.offsetX, sy: e.offsetY, vx: view.x, vy: view.y, menu: e.button === 2 };
    canvas.style.cursor = 'grabbing';
    return;
  }
  if (e.button !== 0 || !nodes.length) return;

  const hit = probe(gx, gy);

  if (hit.kind === 'node-resize') {
    bringToFront(hit.node);
    drag = {
      mode: 'resize-node', node: hit.node, handle: hit.handle, gx, gy,
      start: { x: hit.node.x, y: hit.node.y, w: hit.node.w, h: hit.node.h },
    };
    return;
  }

  if (hit.kind === 'node') {
    const node = hit.node;
    selectedGroup = null;
    if (inTitleBox(node, gx, gy)) {
      node.collapsed = !node.collapsed;
      dirty = true;
      return;
    }
    if (e.altKey) {                       // alt only ever removes
      selection.delete(node);
      dirty = true;
      return;
    }
    // shift or ctrl toggles this node in or out of the selection
    if (e.shiftKey || e.ctrlKey || e.metaKey) {
      if (selection.has(node)) selection.delete(node); else selection.add(node);
    } else if (!selection.has(node)) {
      selection = new Set([node]);
    }
    bringToFront(node);
    const movers = selection.has(node) ? [...selection] : [node];
    drag = { mode: 'move', movers: movers.map(n => ({ n, dx: gx - n.x, dy: gy - n.y })) };
    canvas.style.cursor = 'move';
    dirty = true;
    return;
  }

  if (hit.kind === 'group-resize') {
    selectedGroup = hit.group;
    dirty = true;
    drag = { mode: 'resize-group', group: hit.group, handle: hit.handle, start: hit.group.b.slice() };
    return;
  }

  if (hit.kind === 'group') {
    const g = hit.group;
    selectedGroup = g;
    dirty = true;
    drag = {
      mode: 'move-group', group: g, ox: gx - g.b[0], oy: gy - g.b[1],
      // shift moves the box alone and leaves its contents where they are
      members: e.shiftKey ? [] : nodesInGroup(g).map(n => ({ n, dx: n.x - g.b[0], dy: n.y - g.b[1] })),
    };
    canvas.style.cursor = 'move';
    return;
  }

  // empty canvas: rubber-band select. Shift adds, ctrl inverts and alt
  // subtracts. All three keep whatever is already selected.
  selectedGroup = null;
  const sub = e.altKey;
  const add = e.shiftKey && !sub;
  const invert = (e.ctrlKey || e.metaKey) && !sub;
  if (!add && !invert && !sub) selection = new Set();
  drag = { mode: 'marquee', add, invert, sub, base: new Set(selection) };
  marquee = { x0: gx, y0: gy, x1: gx, y1: gy };
  dirty = true;
});

canvas.addEventListener('pointermove', e => {
  const [gx, gy] = toGraph(e.offsetX, e.offsetY);

  if (!drag) {
    if (!nodes.length) { canvas.style.cursor = 'default'; return; }
    const hit = probe(gx, gy);
    canvas.style.cursor =
      hit.kind === 'node-resize' || hit.kind === 'group-resize' ? CURSORS[hit.handle] :
      hit.kind === 'node' || hit.kind === 'group' ? 'move' : 'default';
    return;
  }

  switch (drag.mode) {
    case 'pan':
      view.x = drag.vx + (e.offsetX - drag.sx);
      view.y = drag.vy + (e.offsetY - drag.sy);
      break;

    case 'move':
      for (const m of drag.movers) {
        m.n.x = Math.round(gx - m.dx);
        m.n.y = Math.round(gy - m.dy);
      }
      break;

    case 'move-group': {
      const g = drag.group;
      g.b[0] = Math.round(gx - drag.ox);
      g.b[1] = Math.round(gy - drag.oy);
      for (const m of drag.members) {
        m.n.x = g.b[0] + m.dx;
        m.n.y = g.b[1] + m.dy;
      }
      break;
    }

    case 'resize-node': {
      const n = drag.node;
      const s = drag.start;
      const dx = gx - drag.gx, dy = gy - drag.gy;
      if (drag.handle.includes('e')) n.w = Math.max(n.minW, Math.round(s.w + dx));
      if (drag.handle.includes('s')) n.h = Math.max(n.minH, Math.round(s.h + dy));
      if (drag.handle.includes('w')) {
        const right = s.x + s.w;
        n.x = Math.round(Math.min(s.x + dx, right - n.minW));
        n.w = right - n.x;
      }
      if (drag.handle.includes('n')) {
        const bottom = s.y + s.h;
        n.y = Math.round(Math.min(s.y + dy, bottom - n.minH));
        n.h = bottom - n.y;
      }
      break;
    }

    case 'resize-group': {
      const b = drag.group.b;
      const s = drag.start;
      if (drag.handle.includes('e')) b[2] = Math.max(GROUP_MIN_W, Math.round(gx - s[0]));
      if (drag.handle.includes('s')) b[3] = Math.max(GROUP_MIN_H, Math.round(gy - s[1]));
      if (drag.handle.includes('w')) {
        const right = s[0] + s[2];
        b[0] = Math.round(Math.min(gx, right - GROUP_MIN_W));
        b[2] = right - b[0];
      }
      if (drag.handle.includes('n')) {
        const bottom = s[1] + s[3];
        b[1] = Math.round(Math.min(gy, bottom - GROUP_MIN_H));
        b[3] = bottom - b[1];
      }
      break;
    }

    case 'marquee': {
      marquee.x1 = gx;
      marquee.y1 = gy;
      const x0 = Math.min(marquee.x0, marquee.x1), x1 = Math.max(marquee.x0, marquee.x1);
      const y0 = Math.min(marquee.y0, marquee.y1), y1 = Math.max(marquee.y0, marquee.y1);
      selection = new Set(drag.add || drag.invert || drag.sub ? drag.base : []);
      for (const n of nodes) {
        const [nx, ny, nw, nh] = nodeRect(n);
        if (!(nx < x1 && nx + nw > x0 && ny < y1 && ny + nh > y0)) continue;
        if (drag.sub || (drag.invert && drag.base.has(n))) selection.delete(n);
        else selection.add(n);
      }
      break;
    }
  }
  dirty = true;
});

function endDrag() {
  if (drag && drag.mode === 'marquee') marquee = null;
  drag = null;
  canvas.style.cursor = 'default';
  dirty = true;
}

canvas.addEventListener('pointerup', e => {
  // a right-click that did not pan opens the menu instead
  if (drag && drag.mode === 'pan' && drag.menu &&
      Math.abs(e.offsetX - drag.sx) < 4 && Math.abs(e.offsetY - drag.sy) < 4) {
    endDrag();
    openMenu(e.offsetX, e.offsetY);
    return;
  }
  endDrag();
});
canvas.addEventListener('pointercancel', endDrag);

