// ComfyUI's own group color choices, cycled as boxes are added.
const GROUP_COLORS = ['#3f789e', '#a1309b', '#88A', '#3f5159', '#653', '#354', '#535', '#8A8'];

const GROUP_PAD = 26;          // breathing room around the nodes inside
const LABEL_SPACE = 22;        // the pack tag that floats above each node

/* Size a box so it comfortably contains the given nodes. */
function fitGroupTo(g, list) {
  if (!list.length) return false;
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const n of list) {
    const [x, y, w, h] = nodeRect(n);
    minX = Math.min(minX, x); minY = Math.min(minY, y - LABEL_SPACE);
    maxX = Math.max(maxX, x + w); maxY = Math.max(maxY, y + h);
  }
  const titleSpace = g.font + 12;
  g.b[0] = Math.round(minX - GROUP_PAD);
  g.b[1] = Math.round(minY - GROUP_PAD - titleSpace);
  g.b[2] = Math.round(maxX - minX + GROUP_PAD * 2);
  g.b[3] = Math.round(maxY - minY + GROUP_PAD * 2 + titleSpace);
  dirty = true;
  return true;
}

/* Wrap the selected nodes in a new comment box. */
function groupSelection() {
  if (!raw) { toast('Nothing loaded', true); return; }
  if (!selection.size) { toast('Select some nodes first', true); return; }

  const rawGroup = {
    title: 'Group',
    bounding: [0, 0, 100, 100],
    color: GROUP_COLORS[groups.length % GROUP_COLORS.length],
    font_size: 24,
    locked: false,
  };
  if (!Array.isArray(raw.groups)) raw.groups = [];
  raw.groups.push(rawGroup);

  const g = { raw: rawGroup, title: rawGroup.title, b: rawGroup.bounding.slice(), color: rawGroup.color, font: 24 };
  fitGroupTo(g, [...selection]);
  groups.push(g);
  selectedGroup = g;
  dirty = true;
  startRename({ kind: 'group', obj: g });
}

function deleteGroup(g) {
  const i = groups.indexOf(g);
  if (i < 0) return;
  groups.splice(i, 1);
  if (raw && Array.isArray(raw.groups)) {
    const j = raw.groups.indexOf(g.raw);
    if (j >= 0) raw.groups.splice(j, 1);
  }
  if (selectedGroup === g) selectedGroup = null;
  dirty = true;
  toast('Comment box deleted');
}

let editor = null;

function stopRename(commit) {
  if (!editor) return;
  const { input, target } = editor;
  editor = null;                       // before removal, so blur does not recurse
  if (commit) {
    const value = input.value.trim();
    if (target.kind === 'node') {
      const n = target.obj;
      n.title = value || n.type;
      if (value && value !== n.type) n.raw.title = value; else delete n.raw.title;
    } else {
      target.obj.title = value;
      target.obj.raw.title = value;
    }
  }
  input.remove();
  dirty = true;
}

/* An input floated over the title being edited. */
function startRename(target) {
  stopRename(true);

  let gx, gy, gw, fontPx;
  if (target.kind === 'node') {
    const n = target.obj;
    gx = n.x + 22; gy = n.y - TITLE_H; gw = nodeW(n) - 26; fontPx = 14;
  } else {
    const g = target.obj;
    gx = g.b[0] + 4; gy = g.b[1] + 2; gw = g.b[2] - 8; fontPx = g.font;
  }

  const input = document.createElement('input');
  input.className = 'rename';
  input.value = target.kind === 'node' ? target.obj.title : target.obj.title;
  input.style.left = (view.x + gx * view.scale) + 'px';
  input.style.top = (view.y + gy * view.scale) + 'px';
  input.style.width = Math.max(80, gw * view.scale) + 'px';
  input.style.height = Math.max(22, (target.kind === 'node' ? TITLE_H : fontPx + 6) * view.scale) + 'px';
  input.style.fontSize = Math.max(12, fontPx * view.scale) + 'px';
  document.body.appendChild(input);
  input.focus();
  input.select();

  input.addEventListener('keydown', e => {
    e.stopPropagation();
    if (e.key === 'Enter') stopRename(true);
    else if (e.key === 'Escape') stopRename(false);
  });
  input.addEventListener('blur', () => stopRename(true));

  editor = { input, target };
}

/* ---------------------------------------------------------------- alignment */

function selected() {
  return [...selection];
}

function needSelection(min) {
  if (selection.size < min) {
    toast(min > 1 ? 'Select two or more nodes first' : 'Select a node first', true);
    return false;
  }
  return true;
}

function arrange(act) {
  const gap = Math.max(0, parseInt(document.getElementById('gap').value, 10) || 0);
  if (!needSelection(2)) return;
  const sel = selected();

  const top = n => n.y - TITLE_H;
  const height = n => nodeH(n) + TITLE_H;

  switch (act) {
    case 'left': {
      const x = Math.min(...sel.map(n => n.x));
      sel.forEach(n => { n.x = x; });
      break;
    }
    case 'right': {
      const r = Math.max(...sel.map(n => n.x + nodeW(n)));
      sel.forEach(n => { n.x = r - nodeW(n); });
      break;
    }
    case 'centerx': {
      const c = sel.reduce((a, n) => a + n.x + nodeW(n) / 2, 0) / sel.length;
      sel.forEach(n => { n.x = Math.round(c - nodeW(n) / 2); });
      break;
    }
    case 'top': {
      const y = Math.min(...sel.map(top));
      sel.forEach(n => { n.y = y + TITLE_H; });
      break;
    }
    case 'bottom': {
      const b = Math.max(...sel.map(n => top(n) + height(n)));
      sel.forEach(n => { n.y = b - height(n) + TITLE_H; });
      break;
    }
    case 'middley': {
      const c = sel.reduce((a, n) => a + top(n) + height(n) / 2, 0) / sel.length;
      sel.forEach(n => { n.y = Math.round(c - height(n) / 2) + TITLE_H; });
      break;
    }
    case 'disth': {
      const s = sel.slice().sort((a, b) => a.x - b.x);
      const first = s[0], last = s[s.length - 1];
      const span = (last.x + nodeW(last)) - first.x;
      const used = s.reduce((a, n) => a + nodeW(n), 0);
      const g = (span - used) / (s.length - 1);
      let x = first.x;
      for (const n of s) { n.x = Math.round(x); x += nodeW(n) + g; }
      break;
    }
    case 'distv': {
      const s = sel.slice().sort((a, b) => top(a) - top(b));
      const first = s[0], last = s[s.length - 1];
      const span = (top(last) + height(last)) - top(first);
      const used = s.reduce((a, n) => a + height(n), 0);
      const g = (span - used) / (s.length - 1);
      let y = top(first);
      for (const n of s) { n.y = Math.round(y) + TITLE_H; y += height(n) + g; }
      break;
    }
    case 'stackv': {
      const s = sel.slice().sort((a, b) => top(a) - top(b));
      const x = Math.min(...s.map(n => n.x));
      let y = top(s[0]);
      for (const n of s) {
        n.x = x;
        n.y = Math.round(y) + TITLE_H;
        y += height(n) + gap;
      }
      break;
    }
    case 'matchw': case 'matchh': {
      // the topmost node is the reference, so a column matches its header
      const ref = sel.reduce((a, n) => (top(n) < top(a) ? n : a), sel[0]);
      for (const n of sel) {
        if (act === 'matchw') n.w = Math.max(n.minW, ref.w);
        else n.h = Math.max(n.minH, ref.h);
      }
      break;
    }
    case 'stackh': {
      const s = sel.slice().sort((a, b) => a.x - b.x);
      const y = Math.min(...s.map(top)) + TITLE_H;
      let x = s[0].x;
      for (const n of s) {
        n.y = y;
        n.x = Math.round(x);
        x += nodeW(n) + gap;
      }
      break;
    }
  }
  dirty = true;
}

/* ------------------------------------------------------------------ viewport */

function bounds() {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const push = (x, y, w, h) => {
    minX = Math.min(minX, x); minY = Math.min(minY, y);
    maxX = Math.max(maxX, x + w); maxY = Math.max(maxY, y + h);
  };
  for (const n of nodes) push(...nodeRect(n));
  for (const g of groups) push(g.b[0], g.b[1], g.b[2], g.b[3]);
  if (!isFinite(minX)) return null;
  return { minX, minY, maxX, maxY };
}

function fit() {
  const b = bounds();
  if (!b) return;
  const pad = 60;
  const sw = innerWidth - pad * 2, sh = innerHeight - pad * 2;
  const scale = Math.min(sw / (b.maxX - b.minX), sh / (b.maxY - b.minY), 1.5);
  view.scale = Math.max(0.02, scale);
  view.x = pad + (sw - (b.maxX - b.minX) * view.scale) / 2 - b.minX * view.scale;
  view.y = pad + (sh - (b.maxY - b.minY) * view.scale) / 2 - b.minY * view.scale;
  dirty = true;
}

