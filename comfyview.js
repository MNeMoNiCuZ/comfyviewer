function openMenu(sx, sy) {
  closeMenu();
  if (!nodes.length) return;
  const [gx, gy] = toGraph(sx, sy);
  const hit = probe(gx, gy);
  const items = [];

  if (hit.kind === 'group' || hit.kind === 'group-resize') {
    const g = hit.group;
    selectedGroup = g;
    dirty = true;
    items.push({ label: 'Rename…', fn: () => startRename({ kind: 'group', obj: g }) });
    items.push({ label: 'Color', children: colorMenuForGroup(g) });
    items.push({ label: 'Fit to contents', fn: () => {
      if (!fitGroupTo(g, nodesInGroup(g))) toast('That box has no nodes in it', true);
    } });
    items.push({ label: 'Select its nodes', fn: () => { selection = new Set(nodesInGroup(g)); dirty = true; } });
    items.push({ label: 'Delete comment box', cls: 'danger', fn: () => deleteGroup(g) });
  } else if (hit.kind === 'node' || hit.kind === 'node-resize') {
    const n = hit.node;
    const many = selection.size > 1 && selection.has(n);
    const targets = many ? [...selection] : [n];

    items.push({ node: packHeader(n) });
    items.push({ label: 'Rename…', fn: () => startRename({ kind: 'node', obj: n }) });
    items.push({
      label: 'Color',
      children: colorMenuForNodes(targets),
    });
    items.push({ label: n.collapsed ? 'Expand' : 'Collapse', fn: () => { n.collapsed = !n.collapsed; dirty = true; } });
    items.push({
      label: `Select all ${n.type} nodes`,
      fn: () => {
        selection = new Set(nodes.filter(o => o.type === n.type));
        dirty = true;
        toast(`Selected every ${n.type}`);
      },
    });
    if (many) items.push({ label: 'Group selected nodes', fn: groupSelection });
  } else {
    if (selection.size) items.push({ label: 'Group selected nodes', fn: groupSelection });
    items.push({ label: 'Select all', fn: () => { selection = new Set(nodes); dirty = true; } });
    if (selection.size) items.push({ label: 'Clear selection', fn: () => { selection = new Set(); dirty = true; } });
    items.push({ label: 'Fit view', fn: fit });
  }

  buildMenu(items, sx, sy, 0);
}

